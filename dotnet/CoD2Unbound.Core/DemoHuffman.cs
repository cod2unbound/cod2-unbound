namespace CoD2Unbound.Core;

internal static class DemoHuffman
{
    private const int LookupBits = 11;
    private const int Mask = (1 << LookupBits) - 1;
    private static readonly ushort[] Lookup = BuildLookup();

    internal static int Decode(ReadOnlySpan<byte> source, Span<byte> target)
    {
        uint bits = 0;
        int available = 0, read = 0, written = 0;
        while (written < target.Length)
        {
            while (available < LookupBits && read < source.Length)
            {
                bits |= (uint)source[read++] << available;
                available += 8;
            }

            int entry = Lookup[bits & Mask];
            int length = entry >> 8;
            if (length == 0 || length > available)
                break;

            target[written++] = (byte)entry;
            bits >>= length;
            available -= length;
        }
        return written;
    }

