import Foundation

enum ConfigParity {
    static func range(_ value: Range<Int>) -> [Int] { [value.lowerBound, value.upperBound] }
    static func token(_ value: ConfigToken) -> [String: Any] {
        ["span": range(value.range), "bytes": value.value.base64EncodedString(),
         "kind": String(describing: value.kind), "closed": value.closed]
    }
    static func failure(_ value: ConfigTokenization.Failure?) -> Any {
        value.map { String(describing: $0) as Any } ?? NSNull()
    }
    static func diagnostic(_ value: ConfigDiagnostic) -> [String: Any] {
        switch value {
        case .ignoredNULSuffix(let span): return ["kind": "ignoredNulSuffix", "span": range(span)]
        case .commandBufferOverflow: return ["kind": "commandBufferOverflow"]
        case .lineLimit(let span, let discarded): return ["kind": "lineLimit", "span": range(span), "discarded": range(discarded)]
        case .tokenizationFailure(let span, let error): return ["kind": "tokenizationFailure", "span": range(span), "failure": failure(error)]
        case .unterminatedQuote(let span): return ["kind": "unterminatedQuote", "span": range(span)]
        }
    }
    static func document(_ id: String, _ bytes: Data, dialect: ConfigDialect) -> [String: Any] {
        let source = ConfigDocument(data: bytes, dialect: dialect)
        return ["id": id, "dialect": dialect.rawValue, "bytes": bytes.base64EncodedString(),
                "serialized": source.serialized().base64EncodedString(), "canonical": source.isCanonical,
                "commands": source.commands.map { cmd in
                    ["kind": String(describing: cmd.kind), "span": range(cmd.range),
                     "separator": range(cmd.separatorRange), "limited": cmd.splitAtLimit,
                     "failure": failure(cmd.tokenizationFailure),
                     "tokens": cmd.tokens.map(token), "comments": cmd.comments.map(range)]
                },
                "diagnostics": source.diagnostics.map(diagnostic)]
    }
    static func edit(_ id: String, _ input: Data, _ dialect: ConfigDialect, _ action: String,
                     _ name: String, _ value: Data = Data(), asText: String? = nil) -> [String: Any] {
        var source = ConfigDocument(data: input, dialect: dialect)
        var result: [String: Any] = ["id": id, "dialect": dialect.rawValue, "input": input.base64EncodedString(),
                                     "action": action, "name": name, "value": value.base64EncodedString()]
        result["textInput"] = asText
        do {
            switch action {
            case "setSetting":
                if let asText { try source.setSetting(named: name, value: asText) }
                else { try source.setSetting(named: name, value: value) }
            case "setBind":
                if let asText { try source.setBind(key: name, binding: asText) }
                else { try source.setBind(key: name, binding: value) }
            case "removeSetting": try source.removeSetting(named: name)
            case "removeBind": try source.removeBind(key: name)
            default: preconditionFailure("Unknown fixture action")
            }
        } catch { result["error"] = String(describing: error) }
        let effective = action.hasSuffix("Bind") ? source.effectiveBindBytes(key: name) : source.effectiveSettingBytes(named: name)
        result["effective"] = effective.map { $0.base64EncodedString() as Any } ?? NSNull()
        result["effectiveText"] = effective.map { ConfigDocument.text($0) as Any } ?? NSNull()
        result["serialized"] = source.serialized().base64EncodedString()
        result["unresolved"] = source.unresolvedCommands.map { range($0.range) }
        return result
    }
    static func build(catalogURL: URL) throws -> [String: Any] {
        func utf8(_ value: String) -> Data { Data(value.utf8) }
        let canonical = utf8("// generated by Call of Duty, do not modify\r\nunbindall\r\nunbindall\r\nbind TAB \"+scores\"\r\nbind MOUSE1 \"+attack\"\r\nseta name \"^1test\"\r\nseta rate \"25000\"\r\n")
        let legacy = utf8("// untouched ") + Data([0x80, 0x92, 0xff]) + utf8("\r\nunknown \"") + Data([0xc3, 0x28, 0x81]) + utf8("\"\nseta name \"^7old\" // keep\r\n") + Data([0, 0xfe, 0x0a])
        let grammar = utf8("seta url http://example.invalid/path\r\nset a \"a;b\";echo two /*/ more\rset a \"unterminated\nbind x \"say \\\"hey\\\"\";vstr z\n") + legacy
        let views = [document("stock-grammar", grammar, dialect: .stock), document("cod2x-grammar", grammar, dialect: .cod2x),
                     document("legacy", legacy, dialect: .stock), document("canonical", canonical, dialect: .stock),
                     document("line-limit", utf8(String(repeating: "x", count: 4095) + "Yset x z\r\n"), dialect: .stock),
                     document("token-limit", utf8(String(repeating: "x ", count: 512) + "x"), dialect: .cod2x),
                     document("empty", Data(), dialect: .cod2x)]
        let tokenInputs: [(String, Data, Int, Int)] = [
            ("verbatim-remainder", utf8("set   x /*/ \"this\"") + Data([0, 65]), 2, 8),
            ("token-buffer", utf8(String(repeating: "a", count: 8704)), 0, 0),
            ("exact-token-limit", utf8(String(repeating: "z ", count: 511) + "z"), 0, 0),
            ("unterminated-comment", utf8("/* never closed"), 0, 3),
            ("dialect-url", utf8("http://host"), 0, 0)
        ]
        let tokens: [[String: Any]] = ConfigDialect.allParityDialects.flatMap { dialect in
            tokenInputs.map { id, input, limit, offset in
                let parsed = ConfigDocument.tokenize(data: input, dialect: dialect, tokenLimit: limit, byteOffset: offset)
                return ["id": "\(dialect.rawValue)-\(id)", "dialect": dialect.rawValue,
                        "bytes": input.base64EncodedString(), "limit": limit, "offset": offset,
                        "tokens": parsed.tokens.map(token), "comments": parsed.comments.map(range), "failure": failure(parsed.failure)]
            }
        }
        let edits = [
            edit("edit-single-byte", legacy, .stock, "setSetting", "name", Data([94, 49, 0xe9, 0x80])),
            edit("append-before-nul", legacy, .cod2x, "setSetting", "cl_new", asText: "café"),
            edit("canonical-insert-binding", canonical, .stock, "setBind", "SPACE", utf8("+moveup")),
            edit("canonical-remove-bind", canonical, .cod2x, "removeBind", "MOUSE1"),
            edit("canonical-insert-setting", canonical, .cod2x, "setSetting", "cg_test", utf8("1")),
            edit("canonical-remove-setting", canonical, .stock, "removeSetting", "NAME"),
            edit("remove-direct-duplicates", utf8("seta n 1; N 2;reset n\n"), .stock, "removeSetting", "n"),
            edit("append-after-dynamic", utf8("seta r \"1\"\ntoggle r\n"), .cod2x, "setSetting", "r", utf8("3")),
            edit("replace-bind", utf8("bind x +attack;unbind X;echo z"), .cod2x, "setBind", "X", utf8("say \"go\"")),
            edit("append-after-unbind", utf8("bind x +attack;unbind x\n"), .stock, "setBind", "X", utf8("say \"go\"")),
            edit("remove-bind-alias", utf8("bind 0x3b +attack;bind SEMICOLON +moveup\n"), .cod2x, "removeBind", "SEMICOLON"),
            edit("preserve-comment", utf8("seta x old /*keep*/ second\n"), .stock, "setSetting", "x", utf8("new")),
            edit("reject-command-redistribution", utf8("bind x +attack;echo x\n"), .cod2x, "setBind", "x", utf8("say \"a;b\"")),
            edit("reject-unsafe-value", Data(), .stock, "setSetting", "value", utf8("ends\\")),
            edit("reject-unsafe-binding", Data(), .stock, "setBind", "TAB", Data([0])),
            edit("reject-non-latin1", Data(), .cod2x, "setBind", "z", asText: "🎮"),
            edit("reject-name", Data(), .stock, "setSetting", "not a name", utf8("1")),
            edit("reject-key", Data(), .stock, "removeBind", "NO_SUCH_KEY"),
            edit("long-binding", Data(), .stock, "setBind", "x", utf8(String(repeating: "x", count: 1024))),
            edit("long-command", Data(), .stock, "setSetting", "x", utf8(String(repeating: "y", count: 4094))),
            edit("command-buffer", utf8(String(repeating: "\n", count: 65535)), .cod2x, "setSetting", "x", utf8("1"))
        ]
        let keys = ["0x3b", "0xAZ", "0X3b", "MOUSE5", "A", "a", "kp_plus", "181", "é", "COMMAND"].map { name in
            let folded = ConfigDocument.keyNumber(name)
            return ["name": name, "folded": folded as Any? ?? NSNull(),
                    "exact": ConfigDocument.keyNumber(name, folding: false) as Any? ?? NSNull(),
                    "spelling": folded.map { ConfigDocument.keySpelling($0) as Any } ?? NSNull()]
        }
        return ["documents": views, "tokenizations": tokens, "edits": edits, "keys": keys, "catalogue": try catalogue(catalogURL)]
    }

    static func catalogue(_ url: URL) throws -> [String: Any] {
        let data = try Data(contentsOf: url)
        let catalog = try ConfigCatalog(data: data)
        let modes = ConfigCatalogMode.allCases
        let groups = catalog.groups.map { group in
            ["id": group.id.rawValue, "title": group.title,
             "settings": catalog.settings(in: group.id).map(\.name), "commands": catalog.commands(in: group.id).map(\.name),
             "guided": Dictionary(uniqueKeysWithValues: modes.map { ($0.rawValue, catalog.guidedSettings(in: group.id, mode: $0).map(\.name)) })]
        }
        let encoder = JSONEncoder()
        func fact(_ value: ConfigCatalogFact?) throws -> Any {
            guard let value else { return NSNull() }
            return try JSONSerialization.jsonObject(with: encoder.encode(value))
        }
        let settings: [[String: Any]] = try ["SENSITIVITY", "r_mode", "r_lodScale", "cl_matchSummaries", "m_enable", "r_vsync", "fs_homepath", "scr_sd_roundlimit", "unknown_test_setting"].map { name in
            guard let setting = catalog.setting(named: name) else { return ["query": name] }
            let variants: [[String: Any]] = try modes.compactMap { mode in
                guard let variant = setting.variant(for: mode) else { return nil }
                return ["mode": mode.rawValue, "flags": variant.flags, "editable": setting.isEditable(in: mode),
                        "type": variant.type?.rawValue as Any? ?? NSNull(), "default": try fact(variant.defaultValue),
                        "minimum": try fact(variant.minimum), "maximum": try fact(variant.maximum), "enumValues": try fact(variant.enumValues)]
            }
            return ["query": name, "name": setting.name, "title": setting.title, "group": setting.group.rawValue,
                    "availability": setting.availability.rawValue, "variants": variants]
        }
        let commands: [[String: Any]] = ["MP_QUICKMESSAGE", "quickmessage", "+attack"].map { name in
            guard let command = catalog.command(named: name) else { return ["query": name] }
            return ["query": name, "name": command.name, "bindable": command.bindable,
                    "modes": modes.filter { command.variant(for: $0) != nil }.map(\.rawValue)]
        }
        var object = try JSONSerialization.jsonObject(with: data) as! [String: Any]
        var entries = object["settings"] as! [[String: Any]]
        var duplicate = entries[0]
        duplicate["name"] = (duplicate["name"] as! String).uppercased()
        entries.append(duplicate)
        let rejected: [String: Bool] = try [
            "unknownSchema": ["schemaVersion": 999],
            "duplicateSetting": ["settings": entries],
            "missingGroups": ["groups": []]
        ].mapValues { mutation in
            for (key, value) in mutation { object[key] = value }
            defer { object = (try? JSONSerialization.jsonObject(with: data) as? [String: Any]) ?? [:] }
            let bytes = try JSONSerialization.data(withJSONObject: object)
            return (try? ConfigCatalog(data: bytes)) == nil
        }
        return ["revision": catalog.sourceRevision, "settingCount": catalog.settings.count,
                "commandCount": catalog.commands.count, "schemaVersion": catalog.schemaVersion,
                "groups": groups, "settings": settings, "commands": commands, "rejected": rejected]
    }
}

private extension ConfigDialect {
    static let allParityDialects: [Self] = [.stock, .cod2x]
}
